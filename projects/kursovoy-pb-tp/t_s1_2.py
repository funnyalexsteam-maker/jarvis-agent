def s1(rp, R):
    P, F = rp.p, fmt
    mix, ins, comp_lim = R["mix"], R["inside"], R["comp_limits"]
    v22 = calc.vapor(22.0, mix)
    v38 = calc.vapor(R["inp"]["t_air_max"], mix)
    rp.h1("1 Анализ пожаровзрывоопасных свойств веществ, обращающихся в технологическом процессе")
    P("Данные о веществах и материалах необходимы для определения категории помещения (теплота сгорания, "
      "количество, скорость испарения, молекулярная масса, плотность паров, концентрация насыщенных паров при "
      "расчетной температуре, максимальное давление взрыва, стехиометрическая концентрация при горении); для "
      "обеспечения безопасности технологического процесса (температура вспышки, температурные и концентрационные "
      "пределы распространения пламени, температура тления, условия теплового самовозгорания, минимальная энергия "
      "зажигания и др.); для выбора огнепреграждающих устройств (безопасный экспериментальный зазор, максимальная "
      "скорость распространения пламени).")
    P("Классификация веществ и материалов по пожаровзрывоопасности и пожарной опасности используется для "
      "установления требований пожарной безопасности при получении веществ и материалов, применении, хранении, "
      "транспортировании, переработке и утилизации.")
    P("Перечень показателей, необходимых для оценки пожаровзрывоопасности и пожарной опасности веществ и "
      "материалов в зависимости от их агрегатного состояния, приведен в таблице 1 Приложения к [3].")
    P("В краскоприготовительном отделении окрасочно-сушильного цеха обращаются: растворитель Р-4 (смесь "
      "толуола, ацетона и н-бутилацетата), полуфабрикат краски (70 % смолы и 30 % растворителя), готовая краска "
      "(20 % смолы и 80 % растворителя), а также природный газ (метан) для обогрева сушильной камеры. "
      "Согласно Федеральному закону № 123-ФЗ [1] жидкость, температура вспышки которой в закрытом тигле не "
      "превышает 61 °C, относится к легковоспламеняющимся жидкостям (ЛВЖ). Все компоненты растворителя Р-4 "
      "удовлетворяют этому условию. Значения показателей пожароопасности принимаются по справочной литературе "
      "[12, 17] и приложению 10 методических указаний [20].")
    P("В таблице 1 приведены пожаровзрывоопасные свойства всех веществ, обращающихся в производстве, включая "
      "сырьё, готовую продукцию, вспомогательные вещества, отходы и выбросы.")
    rp.table_title("1.1", "Пожароопасные свойства веществ и материалов, обращающихся в технологическом процессе")

    def lim(k):
        tn, tv = comp_lim[k]
        return f"{F(tn,0)} ({F(COMP[k]['lel'],2)})", f"{F(tv,0)} ({F(COMP[k]['uel'],1)})"

    def row(n, k, extra):
        a, b = lim(k)
        c = COMP[k]
        return [str(n), c["name"] + f"\n{c['formula']}", "жидкость", "ЛВЖ", F(c["t_flash"], 0), "–",
                F(c["t_auto"], 0), a, b, extra]
    tn, tv = ins["tn"], ins["tv"]
    Qmix = sum(mix["w"][k] * COMP[k]["Qn"] for k in mix["w"])
    rows = [["№\nп/п", "Наименование веществ", "Агрегат-\nное\nсостояние", "Горюч.", "Т_{всп},\n°C", "Т_{воспл},\n°C",
             "Т_{с.воспл},\n°C", "НТПВ, °C\n(НКПВ, %)", "ВТПВ, °C\n(ВКПВ, %)", "Другие свойства"],
            row(1, "acetone", f"M = {F(COMP['acetone']['M'],2)}; Q_{{н}} = {COMP['acetone']['Qn']} кДж/кг; "
                              f"ρ = {COMP['acetone']['rho']:.0f} кг/м³; ГОСТ IEC 60079: IIA-T1"),
            row(2, "toluene", f"M = {F(COMP['toluene']['M'],2)}; Q_{{н}} = {COMP['toluene']['Qn']} кДж/кг; "
                              f"ρ = {COMP['toluene']['rho']:.0f} кг/м³; IIA-T1"),
            row(3, "butylacetate", f"M = {F(COMP['butylacetate']['M'],2)}; Q_{{н}} = {COMP['butylacetate']['Qn']} кДж/кг; "
                                   f"ρ = {COMP['butylacetate']['rho']:.0f} кг/м³; IIA-T2")]
    rp.table(rows, [8, 30, 20, 14, 13, 14, 15, 20, 20, 26], size=9,
             align=["center", "left", "center", "center", "center", "center", "center", "center", "center", "left"])
    rp.h2("1.1 Выбор наиболее опасного вещества")
    P("По методическим указаниям [20] из нескольких ЛВЖ наиболее опасным веществом является жидкость с наименьшей "
      f"температурой вспышки. По таблице 1: ацетон t_{{всп}} = {F(COMP['acetone']['t_flash'],0)} °C, толуол "
      f"t_{{всп}} = {F(COMP['toluene']['t_flash'],0)} °C, н-бутилацетат t_{{всп}} = {F(COMP['butylacetate']['t_flash'],0)} °C. "
      "Все три вещества — ЛВЖ, причём наименьшую температуру вспышки имеет ацетон, поэтому он принят наиболее "
      "опасным веществом. Дальнейшие расчёты (разделы 3, 7 и 8) выполняются для ацетона; его количество в "
      "аппарате определяется долей в растворителе Р-4.")
    rp.h2("1.2 Определение количества наиболее опасного вещества")
    P("Массовые доли компонентов растворителя Р-4 известны по составу (п. 3 раздела «Исходные данные»). Объёмная доля "
      "наиболее опасного вещества:")
    rp.formula(r"\varphi_{v}=\frac{w_{h}/\rho_{h}}{\sum (w_{i}/\rho_{i})}", "1.1")
    P("Масса наиболее опасного вещества в аппарате с объёмом жидкости V_{ж}:")
    rp.formula(r"m_{h}=V_{ж}\cdot \varphi_{v}\cdot \rho_{h}", "1.2")
    P("Давление насыщенного пара вещества при рабочей температуре определяется по уравнению Антуана (константы "
      "приведены в приложении «Значения показателей пожарной опасности и коэффициентов уравнения Антуана» [20]):")
    rp.formula(r"\lg P_{н}=A-\frac{B}{C_{A}+t_{р}}", "1.3")
    rows = [["Компонент", "w, %", "ρ, кг/м³", "φ_{v}, %", "Масса в смесителе, кг"]]
    Vzh = R["inside"]["Vzh"]
    for k in ("toluene", "acetone", "butylacetate"):
        rows.append([COMP[k]["name"], F(100 * mix["w"][k], 0), F(COMP[k]["rho"], 0), F(100 * mix["vol"][k], 1),
                     F(Vzh * mix["vol"][k] * COMP[k]["rho"], 1)])
    rows.append(["Растворитель Р-4", "100", F(mix["rho"], 1), "100,0", F(Vzh * mix["rho"], 1)])
    P("Состав растворителя и количество компонентов в смесителе приведены в таблице 2.")
    rp.table_title("1.2", f"Состав растворителя Р-4 и количество компонентов в смесителе (V_{{ж}} = {F(Vzh,2)} м³)")
    rp.table(rows, [52, 24, 32, 28, 44], size=12, align=["left"] + ["center"] * 4)
    Ph22, Ph38 = calc.p_sat(COMP["acetone"], 22.0), calc.p_sat(COMP["acetone"], R["inp"]["t_air_max"])
    P(f"Для ацетона φ_{{v}} = ({F(mix['w']['acetone'],2)} / {COMP['acetone']['rho']:.0f}) / "
      f"({F(mix['w']['toluene'],2)} / {COMP['toluene']['rho']:.0f} + {F(mix['w']['acetone'],2)} / {COMP['acetone']['rho']:.0f} + "
      f"{F(mix['w']['butylacetate'],2)} / {COMP['butylacetate']['rho']:.0f}) = {F(mix['vol']['acetone'],3)}; "
      f"m_{{h}} = {F(Vzh,2)} · {F(mix['vol']['acetone'],3)} · {COMP['acetone']['rho']:.0f} = "
      f"{F(Vzh*mix['vol']['acetone']*COMP['acetone']['rho'],1)} кг. Давление насыщенного пара ацетона "
      f"(A = {F(COMP['acetone']['A'],5)}; B = {F(COMP['acetone']['B'],3)}; C_{{A}} = {F(COMP['acetone']['C'],3)}): при рабочей температуре "
      f"{F(R['inside']['t'],0)} °C P_{{н}} = {F(Ph22,2)} кПа; при максимальной температуре воздуха региона "
      f"({F(R['inp']['t_air_max'],0)} °C) P_{{н}} = {F(Ph38,2)} кПа.")
    P(f"Вывод. Все обращающиеся в отделении жидкости относятся к ЛВЖ. Наиболее опасное вещество — ацетон: "
      f"t_{{вспышки}} = {F(COMP['acetone']['t_flash'],0)} °C, температурные пределы воспламенения "
      f"от {F(COMP['acetone']['tn_ref'],0)} до +{F(COMP['acetone']['tv_ref'],0)} °C, концентрационные пределы "
      f"{F(COMP['acetone']['lel'],1)}–{F(COMP['acetone']['uel'],1)} %. Рабочая температура смесителя ({F(R['inside']['t'],0)} °C) "
      "лежит вблизи верхнего температурного предела, поэтому горючая среда над жидкостью в смесителе и мернике "
      "может существовать круглый год, и меры защиты необходимо предусматривать независимо от сезона.")


