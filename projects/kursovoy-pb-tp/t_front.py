def toc(rp, pages):
    """Содержание с точечным заполнителем; pages — {ключ: номер страницы}."""
    rp.h1("Содержание", numbered=False)
    for text, key in TOC_ITEMS:
        par = rp.d.add_paragraph()
        pf = par.paragraph_format
        pf.line_spacing = 1.15
        pf.space_after = Pt(4)
        sub = text[:3] in ("9.1", "9.2", "9.3")
        pf.left_indent = Cm(1.0 if sub else 0)
        pf.right_indent = Cm(1.0)
        pf.tab_stops.add_tab_stop(Mm(180) - Mm(0), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
        add_runs(par, text + "\t" + str(pages.get(key, "")), size=14 if not sub else 13)
        # номер страницы выступает за правое поле текста
        pf.right_indent = Cm(0)


