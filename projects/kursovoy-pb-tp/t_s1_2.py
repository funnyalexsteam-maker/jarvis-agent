    rp.table(rows, [95, 85], size=12, align=["left", "left"])
    P(f"Смесители расположены в помещении цеха мерников и растворителей (рис. 2.2) размерами {F(rm['a'],1)} × "
      f"{F(rm['b'],1)} м и высотой {F(rm['h'],1)} м. Площадь пола {F(rm['a']*rm['b'],1)} м², объём помещения "
      f"{F(Vroom,1)} м³, свободный объём (80 % от объёма помещения) {F(0.8*Vroom,1)} м³. В помещении размещены два "
      "мерника растворителя (поз. 2), два смесителя (поз. 3) и два бункера полуфабриката (поз. 4); насосы "
      "подачи растворителя и краски расположены в смежном помещении насосной.")
    rp.image(HERE_IMG("fig_plan_doc.png"), 165, "Рисунок 2.2 – План помещения цеха мерников и растворителей (М 1:100)")
    rp.image(HERE_IMG("fig_section_doc.png"), 165, "Рисунок 2.3 – Разрез 1–1 помещения")


