def s1(rp, R):
    P, F = rp.p, fmt
    mix, ins, comp_lim = R["mix"], R["inside"], R["comp_limits"]
    v22 = calc.vapor(22.0, mix)
    v38 = calc.vapor(R["inp"]["t_air_max"], mix)
    rp.h1("1. Анализ пожаровзрывоопасных свойств веществ, обращающихся в технологическом процессе")
    P("Данные о свойствах веществ необходимы для определения категории помещения (теплота сгорания, "
      "количество, скорость испарения, молекулярная масса, плотность паров, концентрация насыщенных паров при "
      "расчётной температуре, стехиометрическая концентрация), для обеспечения безопасности технологического "
      "процесса (температура вспышки, температурные и концентрационные пределы распространения пламени, "
      "температура самовоспламенения) и для выбора огнепреграждающих устройств. Показатели принимаются по "
      "справочной литературе [12, 17] и приложению 10 методических указаний [20].")
    P("В краскоприготовительном отделении окрасочно-сушильного цеха обращаются: растворитель Р-4 (смесь "
      "толуола, ацетона и н-бутилацетата), полуфабрикат краски (70 % смолы и 30 % растворителя), готовая краска "
      "(20 % смолы и 80 % растворителя), а также природный газ (метан) для обогрева сушильной камеры. "
      "Согласно Федеральному закону № 123-ФЗ [1] жидкость, температура вспышки которой в закрытом тигле не "
      "превышает 61 °C, относится к легковоспламеняющимся жидкостям (ЛВЖ). Все компоненты растворителя Р-4 "
      "удовлетворяют этому условию.")
    rp.table_title("1.1", "Пожароопасные свойства веществ и материалов, обращающихся в технологическом процессе")

    def lim(k):
        tn, tv = comp_lim[k]
        return f"{F(tn,0)} ({F(COMP[k]['lel'],2)})", f"{F(tv,0)} ({F(COMP[k]['uel'],1)})"

    def row(n, k, extra):
        a, b = lim(k)
        c = COMP[k]
        return [str(n), c["name"] + f"\n{c['formula']}", "жидкость", "ЛВЖ", F(c["t_flash"], 0), "–",
                F(c["t_auto"], 0), a, b, extra]
    tn, tv = ins["tn"], ins["tv"]
    Qmix = sum(mix["w"][k] * COMP[k]["Qn"] for k in mix["w"])
    rows = [["№\nп/п", "Наименование веществ", "Агрегат-\nное\nсостояние", "Горюч.", "Т_{всп},\n°C", "Т_{воспл},\n°C",
             "Т_{с.воспл},\n°C", "НТПВ, °C\n(НКПВ, %)", "ВТПВ, °C\n(ВКПВ, %)", "Другие свойства"],
            row(1, "acetone", f"M = {F(COMP['acetone']['M'],2)}; Q_{{н}} = {COMP['acetone']['Qn']} кДж/кг; "
                              f"ρ = {COMP['acetone']['rho']:.0f} кг/м³; ГОСТ IEC 60079: IIA-T1"),
            row(2, "toluene", f"M = {F(COMP['toluene']['M'],2)}; Q_{{н}} = {COMP['toluene']['Qn']} кДж/кг; "
                              f"ρ = {COMP['toluene']['rho']:.0f} кг/м³; IIA-T1"),
            row(3, "butylacetate", f"M = {F(COMP['butylacetate']['M'],2)}; Q_{{н}} = {COMP['butylacetate']['Qn']} кДж/кг; "
                                   f"ρ = {COMP['butylacetate']['rho']:.0f} кг/м³; IIA-T2"),
            ["4", "Растворитель Р-4 (смесь: толуол 62 %, ацетон 26 %, н-бутил-ацетат 12 %)", "жидкость", "ЛВЖ",
             f"{F(tn,0)}*", "–", "330", f"{F(tn,1)} ({F(v22['lel'],2)})", f"{F(tv,1)} ({F(v22['uel'],1)})",
             f"ρ = {F(mix['rho'],0)} кг/м³; Q_{{н}} = {F(Qmix,0)} кДж/кг; расчётные значения по компонентам (п. 1.2)"],
            ["5", "Готовая краска (20 % смолы + 80 % Р-4)", "жидкость", "ЛВЖ", "как у Р-4", "–", "330", "как у Р-4",
             "как у Р-4", "показатели опасности определяются растворителем; смола пожароопасных паров не образует"],
            ["6", "Метан CH_{4} (газ для сушильной камеры)", "газ", "ГГ", "–", "–", "537", "– (5,0)", "– (15,0)",
             f"M = 16,04; Q_{{н}} = 50000 кДж/кг; легче воздуха (0,55)"]]
    rp.table(rows, [8, 30, 16, 12, 13, 13, 15, 19, 19, 35], size=9,
             align=["center", "left", "center", "center", "center", "center", "center", "center", "center", "left"])
    P("* Для смеси Р-4 температура вспышки принята равной нижнему температурному пределу распространения пламени "
      "(с небольшим запасом в сторону опасности). Температура воспламенения для ЛВЖ в расчётах не используется.",
      indent=False, size=12, line=1.0, space_after=6)
    rp.h2("1.1 Выбор наиболее опасного вещества")
    P("По методическим указаниям [20] из нескольких ЛВЖ наиболее опасной является жидкость с наименьшей "
      f"температурой вспышки. Из компонентов растворителя такой жидкостью является ацетон (t_{{всп}} = "
      f"{F(COMP['acetone']['t_flash'],0)} °C). Вклад ацетона в пары над смесью определяется его высокой "
      f"летучестью: при 22 °C в паре над Р-4 содержится {F(100*v22['y']['acetone'],0)} % ацетона, "
      f"{F(100*v22['y']['toluene'],0)} % толуола и {F(100*v22['y']['butylacetate'],1)} % н-бутилацетата (мольные доли). "
      "Поэтому дальнейшие расчёты выполняются для растворителя Р-4 как смеси, а горючие свойства паров "
      "определяются в основном ацетоном.")
    rp.h2("1.2 Расчёт свойств смеси Р-4")
    P("Мольные доли компонентов в жидкой фазе определяются по массовым долям w_{i}:")
    rp.formula(r"x_{i}=\frac{w_{i}/M_{i}}{\sum (w_{j}/M_{j})}", "1.1")
    P("Давление насыщенного пара компонента над раствором находится по закону Рауля, а давление насыщенного "
      "пара чистого вещества — по уравнению Антуана (константы приведены в приложении 10 [20]):")
    rp.formula(r"P_{i}=x_{i}\cdot P_{i}^{0},\q \lg P_{i}^{0}=A-\frac{B}{C_{A}+t}", "1.2")
    P("Концентрационные пределы распространения пламени паров смеси рассчитываются по правилу Ле Шателье, "
      "где y_{i} — мольная доля компонента в паровой фазе:")
    rp.formula(r"C_{н(в)}^{см}=\frac{100}{\sum (y_{i}/C_{н(в),i})}", "1.3")
    P("Температурные пределы распространения пламени определяются как температуры, при которых концентрация "
      "насыщенного пара равна соответственно нижнему и верхнему концентрационному пределу:")
    rp.formula(r"t_{н(в)}=\frac{B}{A-\lg [C_{н(в)}\cdot P_{0}/100]}-C_{A}", "1.4")
    P(f"Результаты расчёта для компонентов раствора при рабочей температуре {F(ins['t'],0)} °C приведены в "
      "таблице 1.2. Использованы справочные значения НКПВ и ВКПВ компонентов: ацетон 2,7 и 13,0 %, толуол 1,27 "
      "и 7,0 %, н-бутилацетат 1,35 и 7,5 % (об.).")
    rp.table_title("1.2", "Состав раствора и насыщенного пара Р-4 при t = 22 °C")
    rws = [["Компонент", "w, %", "x_{i}", f"P^{{0}}_{{i}}, кПа", "P_{i}, кПа", "y_{i}"]]
    for k in ("toluene", "acetone", "butylacetate"):
        rws.append([COMP[k]["name"], F(100 * mix["w"][k], 0), F(mix["x"][k], 4),
                    F(calc.p_sat(COMP[k], 22.0), 2), F(v22["p"][k], 2), F(v22["y"][k], 3)])
    rws.append(["Смесь Р-4", "100", "1,0000", "–", F(v22["ps"], 2), "1,000"])
    rp.table(rws, [50, 22, 26, 30, 28, 24], size=12, align=["left"] + ["center"] * 5)
    P(f"Пары смеси при 22 °C имеют молярную массу {F(v22['M'],1)} кг/кмоль, нижний предел распространения пламени "
      f"{F(v22['lel'],2)} % и верхний {F(v22['uel'],2)} % (об.). Температурные пределы смеси: нижний "
      f"t_{{н}} = {F(tn,1)} °C, верхний t_{{в}} = {F(tv,1)} °C. При максимальной температуре воздуха региона "
      f"({F(R['inp']['t_air_max'],0)} °C) давление насыщенных паров над смесью составляет {F(v38['ps'],1)} кПа, "
      f"а их концентрация — {F(v38['phi'],1)} % (об.), то есть существенно выше верхнего предела: непосредственно над "
      "поверхностью разлива смесь слишком богата для горения, но по мере разбавления воздухом помещения она "
      "проходит область воспламенения и образует взрывоопасные концентрации в объёме помещения.")
    P("Вывод. Все обращающиеся в отделении жидкости относятся к ЛВЖ, причём для растворителя Р-4 нижний "
      "температурный предел распространения пламени лежит ниже 0 °C, а верхний — вблизи рабочей температуры "
      "аппарата. Это означает, что горючая среда над поверхностью жидкости в смесителе и мернике может "
      "существовать круглый год, и меры защиты необходимо предусматривать независимо от сезона.")


