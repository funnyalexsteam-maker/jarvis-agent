            ["Объём жидкости V_{ж}, м³", F(mx["V"] * mx["eps"], 2)],
            ["Свободный (паровоздушный) объём, м³", F(mx["V"] * (1 - mx["eps"]), 2)],
            ["Рабочая температура жидкости t_{р}, °C", F(mx["t_tech"], 0)],
            ["Давление в аппарате и трубопроводах P_{р}, МПа (абс.)", F(mx["P_mpa"], 2)],
            ["Диаметр трубопроводов, мм", F(mx["d_mm"], 0)],
            ["Длина подводящего / отводящего трубопровода, м", f"{F(mx['L_in'],0)} / {F(mx['L_out'],0)}"],
            ["Производительность насоса, л/с", F(mx["q_lps"], 1)],
            ["Способ отключения трубопроводов", "ручной (расчётное время 300 с)"],
