"""Разделы 7–8: расчёт критериев пожарной опасности и категория помещения."""
import math
import calc
from calc import COMP
from dochelp import *


def s7(rp, R):
    P, F = rp.p, fmt
    I, acc, mix = R["inp"], R["acc"], R["mix"]
    mx, rm, T = I["mixer"], I["room"], I["t_air_max"]
    rp.h1("7 Расчёт критериев пожарной опасности технологического процесса")
    P("В данном разделе по методике приложений 9 и 7 методических указаний [20] и СП 12.13130.2009 [9] выполнен "
      "расчёт количества горючих веществ, поступающих в помещение при полном разрушении технологического "
      "оборудования. Полученные величины — масса пролитой жидкости, площадь и интенсивность испарения, масса паров, "
      "объём зоны взрывоопасных концентраций и время её образования — служат исходными данными для определения "
      "категории помещения (раздел 8).")
    rp.h2("7.1 Расчётный сценарий и исходные данные")
    P("В качестве расчётной аварии принимается полное разрушение смесителя растворителя (поз. 3) в помещении цеха "
      "мерников и растворителей. Предполагается, что: происходит авария одного аппарата; все его содержимое поступает в "
      "помещение; одновременно происходит утечка жидкости из питающего и отводящего трубопроводов в течение времени, "
      f"необходимого для отключения (ручное отключение — {F(acc['tau_off'],0)} с [9]); жидкость растекается по полу "
      "помещения; общеобменная вентиляция не учитывается (самый неблагоприятный вариант); расчётная температура жидкости "
      f"равна максимальной температуре воздуха в регионе t_{{р}} = {F(T,0)} °C (СП 131.13330 [11]). Расчёт выполняется "
      "для наиболее опасного вещества, определённого в разделе 1, — ацетона (t_{всп} = −18 °C); его количество "
      "определяется долей в растворителе Р-4.")
    rp.h2("7.2 Масса жидкости, поступившей в помещение")
    P("Масса горючей жидкости определяется по формуле")
    rp.formula(r"m_{ж}=\rho_{ж}\cdot (V_{ап}\cdot \varepsilon +\sum q_{i}\cdot \tau_{i}+\sum l_{j}\cdot f_{j})", "7.1")
    P(f"где ρ_{{ж}} = {F(acc['rho'],1)} кг/м³ — плотность раствора Р-4 (по аддитивности объёмов компонентов); "
      f"V_{{ап}} = {F(mx['V'],1)} м³; ε = {F(mx['eps'],1)}; q = {F(mx['q_lps']/1000,4)} м³/с — производительность насоса; "
      f"τ = {F(acc['tau_off'],0)} с — время отключения; l_{{j}}, f_{{j}} — длина и сечение трубопроводов: "
      f"f = π · d² / 4 = 3,1416 · {F(mx['d_mm']/1000,3)}² / 4 = {F(acc['f']*1e3,3)}·10^{{-3}} м², "
      f"Σ l_{{j}} = {F(mx['L_in'],0)} + {F(mx['L_out'],0)} = {F(mx['L_in']+mx['L_out'],0)} м.")
    P(f"Объём жидкости: V_{{ж}} = {F(acc['V_app'],2)} + {F(acc['V_pump'],2)} + {F(acc['V_pipe'],5)} = {F(acc['V_liq'],3)} м³. "
      f"Масса: m_{{ж}} = {F(acc['rho'],1)} · {F(acc['V_liq'],3)} = {F(acc['m_liq'],1)} кг.")
    P(f"Доля наиболее опасного вещества в растворителе (п. 1.2): объёмная доля ацетона φ_{{v}} = {F(100*acc['phi_v'],1)} %. "
      f"Объём ацетона в разлившейся жидкости V_{{h}} = V_{{ж}} · φ_{{v}} = {F(acc['V_liq'],3)} · {F(acc['phi_v'],3)} = "
      f"{F(acc['V_h'],3)} м³; масса ацетона m_{{h}} = V_{{h}} · ρ_{{h}} = {F(acc['V_h'],3)} · {COMP['acetone']['rho']:.0f} = "
      f"{F(acc['m_h'],1)} кг.")
    P("Площадь испарения принимается как минимальная из площади разлива и площади пола помещения:")
    rp.formula(r"F_{И}=\min [F_{р}=f_{р}\cdot V_{ж};\q F_{п}=a\cdot b]", "7.2")
    P(f"Так как растворитель Р-4 содержит более 70 % растворителей по массе, 1 л жидкости разливается на площади "
      f"1 м², то есть f_{{р}} = 1 м²/л [9]. F_{{р}} = 1 · {F(acc['V_liq']*1000,0)} = {F(acc['Fr'],0)} м²; "
      f"F_{{п}} = {F(rm['a'],1)} · {F(rm['b'],1)} = {F(acc['Fp'],1)} м². Следовательно, F_{{И}} = {F(acc['Fi'],1)} м² — "
      "жидкость покрывает весь пол помещения.")
    rp.h2("7.3 Интенсивность испарения и масса паров")
    P("Интенсивность испарения ацетона, не нагретого выше температуры окружающей среды, определяется по формуле")
    rp.formula(r"W=10^{-6}\cdot \eta \cdot \sqrt{M}\cdot P_{н}", "7.3")
    P(f"где η = {F(acc['eta'],1)} — коэффициент по табл. 7.1 [20] при скорости воздушного потока "
      f"{F(mx['u'],1)} м/с (для температуры выше 35 °C принято значение при 35 °C); M = {F(COMP['acetone']['M'],2)} — молярная "
      "масса, кг/кмоль (в формулу подставляется в г/моль); P_{н} — давление насыщенного пара ацетона при "
      f"t_{{р}} = {F(T,0)} °C, кПа, по уравнению Антуана (п. 1.2): P_{{н}} = {F(acc['Pn'],2)} кПа. "
      f"W = 10^{{-6}} · {F(acc['eta'],1)} · √{F(COMP['acetone']['M'],2)} · {F(acc['Pn'],2)} = {F(acc['W']*1e3,3)}·10^{{-3}} кг/(с·м²). "
      "Масса паров, испарившихся за время τ:")
    rp.formula(r"m=W\cdot F_{И}\cdot \tau", "7.4")
    P(f"Время полного испарения ацетона по формуле τ_{{п}} = m_{{h}} / (W · F_{{И}}) = {F(acc['m_h'],1)} / "
      f"({F(acc['W']*1e3,3)}·10^{{-3}} · {F(acc['Fi'],1)}) = {F(acc['tau_full'],0)} с, что "
      f"{'меньше' if acc['tau_full']<3600 else 'больше'} 3600 с, поэтому продолжительность испарения принимается "
      f"τ = {F(acc['tau'],0)} с [9]. Результаты расчёта приведены в таблице 10.")
    rp.table_title("7.1", f"Расчёт испарения ацетона при t = {F(T,0)} °C, F_{{И}} = {F(acc['Fi'],1)} м²")
    rows = [["Вещество", "M, кг/кмоль", "P_{н}, кПа", "W·10^{3},\nкг/(с·м²)", "τ, с", "m, кг"],
            ["Ацетон", F(COMP["acetone"]["M"], 2), F(acc["Pn"], 2), F(acc["W"] * 1e3, 3), F(acc["tau"], 0), F(acc["m"], 1)]]
    rp.table(rows, [40, 30, 30, 32, 24, 24], size=11, align=["left"] + ["center"] * 5)
    P(f"Таким образом, в помещение поступает m = {F(acc['m'],1)} кг паров ацетона. Плотность паров при расчётной "
      f"температуре по формуле ρ_{{п}} = M / [V_{{0}} · (1 + 0,00367 · t_{{р}})] = "
      f"{F(acc['M'],2)} / [22,4135 · (1 + 0,00367 · {F(T,0)})] = {F(acc['rho_p'],2)} кг/м³.")
    rp.h2("7.4 Объём зоны взрывоопасных концентраций и время её образования")
    P(f"Нижний концентрационный предел распространения пламени паров ацетона равен {F(acc['lel'],2)} % (об.). "
      "Пересчёт в кг/м³ выполняется по формуле")
    rp.formula(r"\varphi_{н}^{*}=\frac{M\cdot \varphi_{н}}{V_{t}}", "7.5")
    P(f"φ*_{{н}} = {F(acc['M'],2)} · {F(acc['lel']/100,4)} / {F(acc['Vt'],2)} = {F(acc['lel_kg'],4)} кг/м³. "
      "Объём зоны, в которой может образоваться взрывоопасная концентрация паров:")
    rp.formula(r"V_{ВОК}=\frac{m}{\varphi_{н}^{*}}\cdot K_{б}", "7.6")
    P(f"V_{{ВОК}} = {F(acc['m'],1)} / {F(acc['lel_kg'],4)} · 2 = {F(acc['Vvok'],0)} м³ ≫ V_{{св}} = {F(acc['Vsv'],1)} м³. "
      f"Здесь V_{{св}} = 0,8 · a · b · h = 0,8 · {F(rm['a'],1)} · {F(rm['b'],1)} · {F(rm['h'],1)} = {F(acc['Vsv'],1)} м³. "
      "Взрывоопасная концентрация распространяется на весь свободный объём помещения. Средняя концентрация паров:")
    rp.formula(r"C_{р}=\frac{100\cdot m}{\rho_{п}\cdot V_{св}}", "7.7")
    P(f"C_{{р}} = 100 · {F(acc['m'],1)} / ({F(acc['rho_p'],2)} · {F(acc['Vsv'],1)}) = {F(acc['Cavg'],1)} % (об.), что "
      f"значительно превышает 0,5 · C_{{НКПР}} = {F(0.5*acc['lel'],2)} %. Значение не превышает концентрацию "
      f"насыщения паров ацетона при {F(T,0)} °C (≈{F(calc.vapor(T)['phi'],1)} %), поэтому вся масса паров может "
      "находиться в воздухе помещения.")
    P("Продолжительность нарастания взрывоопасной концентрации в помещении при отсутствии и при наличии "
      "воздухообмена определяется по формулам:")
    rp.formula(r"\tau_{г}=\frac{V_{св}}{q}\cdot \ln \frac{1}{1-\varphi_{н}}", "7.8")
    rp.formula(r"\tau_{г}=\frac{V_{св}}{a+q}\cdot \ln \frac{q}{q-(a+q)\cdot \varphi_{н}}", "7.9")
    P(f"где q = m / (ρ_{{п}} · τ) = {F(acc['m'],1)} / ({F(acc['rho_p'],2)} · {F(acc['tau'],0)}) = {F(acc['q'],4)} м³/с — интенсивность "
      f"поступления паров; a = A · V_{{св}} / 3600 = {F(R['inp']['mixer']['A'],0)} · {F(acc['Vsv'],1)} / 3600 = "
      f"{F(acc['a_v'],3)} м³/с — производительность вентиляции; φ_{{н}} = {F(acc['lel']/100,4)}. "
      f"Без вентиляции τ_{{г}} = {F(acc['tg0'],0)} с ({F(acc['tg0']/60,1)} мин); с вентиляцией τ_{{г}} = "
      f"{F(acc['tg1'],0)} с ({F(acc['tg1']/60,1)} мин). Установившаяся концентрация с учётом вентиляции q / (a + q) = "
      f"{F(acc['c_steady'],1)} % превышает НКПР, то есть общеобменная вентиляция не предотвращает образование "
      "взрывоопасной среды и не может учитываться при категорировании. (Формула (7.9) получена из уравнения "
      "материального баланса помещения dC/dτ = q − (a + q)·C при полном перемешивании и при a = 0 переходит "
      "в формулу (7.8).)")
    # ---------------------------------------------------------- 7.5 зоны НКПР
    rp.h2("7.5 Размеры зоны, ограниченной нижним концентрационным пределом")
    vT = calc.vapor(T, mix)
    Cn = 100.0 * vT["ps"] / 101.0
    m_, rho_p_, Vsv_ = acc["m"], acc["rho_p"], acc["Vsv"]
    Cnkpr = acc["lel"]
    C0 = Cn * (m_ * 100.0 / (Cn * rho_p_ * Vsv_)) ** 0.46
    K1, K2, K3, delta = 1.1958, acc["tau"] / 3600.0, 0.3536, 1.27
    arg = math.log(delta * C0 / Cnkpr)
    X = K1 * rm["a"] * (K2 * arg) ** 0.5
    Y = K1 * rm["b"] * (K2 * arg) ** 0.5
    Zn = K3 * rm["h"] * (K2 * arg) ** 0.5
    P("Для оценки размеров зоны, ограниченной НКПР, применяется методика приложения 6 [20] (для паров ЛВЖ при "
      "подвижности воздушной среды 0,5 м/с). Уровень значимости принят Q(C > C̄) = 0,05, при этом допустимое "
      f"отклонение концентраций δ = {F(delta,2)} (табл. 6.1 [20]). Предэкспоненциальный множитель:")
    rp.formula(r"C_{0}=C_{н}\cdot {(\frac{m\cdot 100}{C_{н}\cdot \rho_{п}\cdot V_{св}})}^{0,46}", "7.10")
    P(f"где C_{{н}} = 100 · P_{{н}} / P_{{0}} = 100 · {F(vT['ps'],2)} / 101 = {F(Cn,1)} % — концентрация насыщенных паров "
      f"при {F(T,0)} °C. C_{{0}} = {F(Cn,1)} · (256,1 · 100 / ({F(Cn,1)} · {F(rho_p_,2)} · {F(Vsv_,1)}))^{{0,46}} = {F(C0,1)} %.".replace("256,1", F(m_, 1)))
    P("Расстояния X_{НКПР}, Y_{НКПР}, Z_{НКПР} находятся по формулам (7.11), (7.12), (7.13):")
    rp.formula(r"X_{НКПР}=K_{1}\cdot l\cdot {(K_{2}\ln \frac{\delta C_{0}}{C_{НКПР}})}^{0,5}", "7.11")
    rp.formula(r"Y_{НКПР}=K_{1}\cdot b\cdot {(K_{2}\ln \frac{\delta C_{0}}{C_{НКПР}})}^{0,5}", "7.12")
    rp.formula(r"Z_{НКПР}=K_{3}\cdot h\cdot {(K_{2}\ln \frac{\delta C_{0}}{C_{НКПР}})}^{0,5}", "7.13")
    P(f"где K_{{1}} = 1,1958; K_{{2}} = T / 3600 = {F(acc['tau'],0)} / 3600 = {F(K2,0)}; K_{{3}} = 0,3536; l = {F(rm['a'],1)} м; "
      f"b = {F(rm['b'],1)} м; h = {F(rm['h'],1)} м; C_{{НКПР}} = {F(Cnkpr,2)} %. ln(δ · C_{{0}} / C_{{НКПР}}) = "
      f"ln({F(delta,2)} · {F(C0,1)} / {F(Cnkpr,2)}) = {F(arg,3)}. Тогда X_{{НКПР}} = {F(K1,4)} · {F(rm['a'],1)} · "
      f"{F(arg,3)}^{{0,5}} = {F(X,1)} м; Y_{{НКПР}} = {F(K1,4)} · {F(rm['b'],1)} · {F(arg,3)}^{{0,5}} = {F(Y,1)} м; "
      f"Z_{{НКПР}} = {F(K3,4)} · {F(rm['h'],1)} · {F(arg,3)}^{{0,5}} = {F(Zn,2)} м.")
    P(f"Горизонтальные размеры зоны (X_{{НКПР}} = {F(X,1)} м > l = {F(rm['a'],1)} м и Y_{{НКПР}} = {F(Y,1)} м > "
      f"b = {F(rm['b'],1)} м) превышают размеры помещения, поэтому зона, ограниченная нижним концентрационным пределом "
      "распространения пламени, занимает всю площадь пола помещения. Это подтверждает вывод п. 7.4 о том, что "
      "взрывоопасная концентрация паров образуется во всём объёме помещения.")
    P("Итоговые результаты расчёта представлены в таблице 11.")
    rp.table_title("7.2", "Результаты расчёта критериев пожарной опасности")
    rows = [["Показатель", "Обозначение", "Значение"],
            ["Масса жидкости, поступившей в помещение", "m_{ж}", f"{F(acc['m_liq'],1)} кг"],
            ["Площадь испарения", "F_{И}", f"{F(acc['Fi'],1)} м²"],
            ["Масса ацетона в разлившейся жидкости", "m_{h}", f"{F(acc['m_h'],1)} кг"],
            ["Масса паров ацетона, поступивших в помещение", "m", f"{F(acc['m'],1)} кг"],
            ["Плотность паров при 38 °C", "ρ_{п}", f"{F(acc['rho_p'],2)} кг/м³"],
            ["НКПР ацетона", "C_{НКПР}", f"{F(acc['lel'],2)} % об."],
            ["Объём зоны ВОК", "V_{ВОК}", f"{F(acc['Vvok'],0)} м³ (весь объём помещения)"],
            ["Средняя концентрация паров", "C_{р}", f"{F(acc['Cavg'],1)} % об."],
            ["Время образования ВОК (с учётом вентиляции)", "τ_{г}", f"{F(acc['tg1']/60,1)} мин"]]
    rp.table(rows, [95, 30, 55], size=12, align=["left", "center", "left"])


