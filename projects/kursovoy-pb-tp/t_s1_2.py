def s2(rp, R):
    P, F = rp.p, fmt
    I = R["inp"]
    mx, rm = I["mixer"], I["room"]
    Vroom = rm["a"] * rm["b"] * rm["h"]
    rp.h1("2 Краткое описание технологического процесса")
    P("Окрасочный цех автомобилестроительного и тракторостроительного заводов предназначен для окраски и сушки "
      "различных деталей машин. Перед окраской поверхность деталей очищают от ржавчины и обезжиривают. "
      "Необходимое количество лакокрасочного материала приготавливается в краскоприготовительном отделении "
      "путём разбавления полуфабриката соответствующим растворителем.")
    rp.h2("2.1 Приготовление краски")
    P("В краскоприготовительном отделении (рис. 1) насосом 1 подаётся необходимое количество растворителя, "
      "которое отмеривается мерником 2 и сливается в лопастной аппарат-растворитель (смеситель) 3. "
      "Одновременно в смеситель из бункера 4 подаётся полуфабрикат краски, состоящий из 70 % смолы и 30 % "
      "растворителя. В смесителе при непрерывной работе мешалки и подогреве горячей водой (до 40 °C на "
      "автомобильном заводе и до 60 °C на тракторном) происходит растворение и разбавление полуфабриката до "
      "готового состава краски: 20 % смолы и 80 % растворителя.")
    P("Готовая краска из смесителя выбирается центробежным насосом 5, продавливается через фильтр 6 для очистки "
      "от твёрдых частиц и поступает в расходные ёмкости 7. Из ёмкостей краска непрерывно циркулирует насосами 8 "
      "по кольцевой линии 9 до окрасочной камеры 17 и обратно.")
    rp.image(HERE_IMG("fig_scheme_small.png"), 172,
             "Рисунок 1 – Принципиальная технологическая схема краскоприготовления и окраски")
    rp.h2("2.2 Окраска и сушка деталей")
    P("Подлежащие окраске детали поступают из соседних цехов на загрузочную площадку 13, навешиваются на конвейер 10 "
      "и доставляются в камеру 12 для механической и химической очистки и обезжиривания (слабые водные растворы "
      "фосфорной кислоты и ПАВ). После промывки детали сушатся в камере 11.")
    P("Очищенные и высушенные детали поступают в окрасочную камеру 17 через открытые проёмы в торцевых стенах. "
      "Камера имеет два рабочих места для окраски пульверизатором. К каждому пульверизатору по гибкому рукаву 18 "
      "подводится краска от циркуляционного кольца, а по отдельному рукаву — сжатый воздух. Камера оборудована "
      "вытяжной вентиляцией; отсасываемый воздух очищается от частиц краски в гидрофильтре (водяная завеса 19). "
      "Стены камеры очищаются от осевшей краски медными скребками раз в неделю, пол — после каждой смены.")
    P("После окраски детали поступают в сушильную камеру 15 терморадиационного типа с газообогревательными "
      "закрытыми панелями 16 (в качестве топлива используется метан). Максимальная температура обогреваемой "
      "поверхности панели — 400 °C. При сушке окрашенной поверхности автомобильных деталей выделяются пары "
      "ацетона, тракторных — пары бензола. Высушенные детали конвейером подаются на разгрузочную площадку 14 и "
      "далее отвозятся тележками в сборочные цехи.")
    rp.h2("2.3 Оборудование и помещения")
    P("Условные обозначения оборудования, принятые на схемах, приведены в таблице 3.")
    rp.table_title("2.1", "Условное обозначение оборудования")
    half = (len(EQUIP) + 1) // 2
    rows = [["Поз.", "Наименование аппаратов", "Поз.", "Наименование аппаратов"]]
    for i in range(half):
        a = EQUIP[i]
        b = EQUIP[i + half] if i + half < len(EQUIP) else ("", "")
        rows.append([a[0], a[1], b[0], b[1]])
    rp.table(rows, [12, 78, 12, 78], size=11, align=["center", "left", "center", "left"])
    P("Расчётным (наиболее опасным) аппаратом по заданию является смеситель-растворитель поз. 3, "
      "размещённый в помещении цеха мерников и растворителей. Его техническая характеристика и параметры "
      "процесса приведены в таблице 4.")
    rp.table_title("2.2", "Техническая характеристика смесителя растворителя (поз. 3)")
    rows = [["Параметр", "Значение"],
            ["Тип аппарата", "вертикальный цилиндрический, лопастной, с обогревом горячей водой"],
            ["Объём аппарата V_{ап}, м³", F(mx["V"], 1)],
            ["Степень заполнения ε", F(mx["eps"], 1)],
            ["Объём жидкости V_{ж}, м³", F(mx["V"] * mx["eps"], 2)],
            ["Свободный (паровоздушный) объём, м³", F(mx["V"] * (1 - mx["eps"]), 2)],
            ["Рабочая температура жидкости t_{р}, °C", F(mx["t_tech"], 0)],
            ["Давление в аппарате и трубопроводах P_{р}, МПа (абс.)", F(mx["P_mpa"], 2)],
            ["Диаметр трубопроводов, мм", F(mx["d_mm"], 0)],
            ["Длина подводящего / отводящего трубопровода, м", f"{F(mx['L_in'],0)} / {F(mx['L_out'],0)}"],
            ["Производительность насоса, л/с", F(mx["q_lps"], 1)],
            ["Способ отключения трубопроводов", "ручной (расчётное время 300 с)"],
            ["Обращающееся вещество", "растворитель Р-4 (толуол 62 %, ацетон 26 %, н-бутилацетат 12 %)"]]
    rp.table(rows, [95, 85], size=12, align=["left", "left"])
    P(f"Смесители расположены в помещении цеха мерников и растворителей (рис. 2) размерами {F(rm['a'],1)} × "
      f"{F(rm['b'],1)} м и высотой {F(rm['h'],1)} м. Площадь пола {F(rm['a']*rm['b'],1)} м², объём помещения "
      f"{F(Vroom,1)} м³, свободный объём (80 % от объёма помещения) {F(0.8*Vroom,1)} м³. В помещении размещены два "
      "мерника растворителя (поз. 2), два смесителя (поз. 3) и два бункера полуфабриката (поз. 4); насосы "
      "подачи растворителя и краски расположены в смежном помещении насосной. Разрез помещения показан на рисунке 3.")
    rp.image(HERE_IMG("fig_plan_doc.png"), 165, "Рисунок 2 – План помещения цеха мерников и растворителей (М 1:100)")
    rp.image(HERE_IMG("fig_section_doc.png"), 165, "Рисунок 3 – Разрез 1–1 помещения")
    rp.h2("2.4 Энергетический потенциал блока")
    m_liq_app = R["acc"]["V_app"] * R["acc"]["rho"]
    w = R["mix"]["w"]
    parts = {k: w[k] * m_liq_app for k in ("toluene", "acetone", "butylacetate")}
    Qsum = sum(parts[k] * COMP[k]["Qn"] * 1000.0 for k in parts)
    P("Каждый блок технологического процесса характеризуется энергетическим потенциалом [14, 15]:")
    rp.formula(r"Q=\sum Q_{нi}\cdot m_{i}", "2.1")
    P("где Q_{нi} — низшая теплота сгорания i-го горючего материала, находящегося в блоке, Дж/кг; m_{i} — масса "
      "i-го горючего материала, кг. За блок принят смеситель поз. 3 с растворителем Р-4 "
      f"(m = V_{{ж}} · ρ = {F(R['acc']['V_app'],2)} · {F(R['acc']['rho'],1)} = {F(m_liq_app,0)} кг). Массы компонентов: "
      f"толуол {F(parts['toluene'],1)} кг, ацетон {F(parts['acetone'],1)} кг, н-бутилацетат {F(parts['butylacetate'],1)} кг. "
      f"Q = {F(parts['toluene'],1)} · {COMP['toluene']['Qn']*1000:.0f} + {F(parts['acetone'],1)} · {COMP['acetone']['Qn']*1000:.0f} + "
      f"{F(parts['butylacetate'],1)} · {COMP['butylacetate']['Qn']*1000:.0f} = {F(Qsum/1e9,1)}·10^{{9}} Дж = "
      f"{F(Qsum/1e9,1)} ГДж. Большой энергетический потенциал блока определяет необходимость мер по "
      "ограничению количества жидкости и аварийному сливу (разд. 9).")


